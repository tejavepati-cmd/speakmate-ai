"use client";

import { Loader2, Sparkles, TriangleAlert, WifiOff } from "lucide-react";
import { Badge } from "@/components/ui/badge";
import { cn } from "@/lib/utils";

type Source = "ai" | "offline" | undefined;

export const OFFLINE_BADGE = "Offline practice — not AI";

/** Compact label for a single reply or message bubble. */
export function SourceBadge({ source, className }: { source?: Source; className?: string }) {
  if (!source) return null;
  if (source === "offline") {
    return (
      <Badge variant="outline" className={cn("border-warning/40 text-warning", className)}>
        <WifiOff className="size-3" aria-hidden="true" />
        {OFFLINE_BADGE}
      </Badge>
    );
  }
  return (
    <Badge variant="success" className={className}>
      <Sparkles className="size-3" aria-hidden="true" />
      AI response
    </Badge>
  );
}

/**
 * Full source disclosure shown with every AI call. Offline responses are never
 * presented as genuine AI output.
 */
export function SourceNotice({
  source,
  error,
  loading,
  className,
}: {
  source?: Source;
  error?: string | null;
  loading?: boolean;
  className?: string;
}) {
  if (loading) {
    return (
      <div className={cn("flex flex-wrap items-center gap-2 text-xs text-muted", className)} role="status" aria-live="polite">
        <Loader2 className="size-4 animate-spin text-primary" aria-hidden="true" />
        <span>Getting feedback…</span>
      </div>
    );
  }

  if (!error && !source) return null;

  return (
    <div className={cn("min-w-0 space-y-2", className)}>
      {error && (
        <div className="rounded-2xl border border-danger/25 bg-danger-soft p-3.5 text-sm text-danger" role="alert">
          <div className="flex flex-wrap items-center gap-2 font-bold">
            <TriangleAlert className="size-4" aria-hidden="true" />
            Could not complete this request
          </div>
          <p className="mt-1 text-xs leading-relaxed">{error}</p>
        </div>
      )}

      {source === "offline" && (
        <>
          <SourceBadge source="offline" />
          <div className="rounded-2xl border border-warning/30 bg-warning/5 p-3.5 text-xs leading-relaxed text-muted" role="note">
            <p className="flex items-center gap-2 font-bold text-foreground">
              <WifiOff className="size-4 shrink-0 text-warning" aria-hidden="true" />
              Online AI is unavailable
            </p>
            <p className="mt-1">
              This is a local, rule-based practice response generated on your device. It is <strong>not</strong> a genuine AI reply and it
              cannot understand context the way an AI can. Check your connection and AI settings to enable online feedback.
            </p>
          </div>
        </>
      )}

      {source === "ai" && !error && (
        <div className="flex flex-wrap items-center gap-2">
          <SourceBadge source="ai" />
          <span className="text-xs text-muted">Generated by your configured online AI provider.</span>
        </div>
      )}
    </div>
  );
}
